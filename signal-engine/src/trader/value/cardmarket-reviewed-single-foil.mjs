export function validateReviewedSingleFoilMappings(rows) {
  const byProduct = new Map();
  for (const row of rows || []) {
    const id = String(row.source_record_id);
    const owners = byProduct.get(id) || [];
    owners.push(row);
    byProduct.set(id, owners);
  }
  const valid = new Set();
  for (const evidence of REVIEWED_SINGLE_FOIL_PRODUCTS) {
    const owners = byProduct.get(evidence.source_record_id) || [];
    if (owners.length !== 1) continue;
    const row = owners[0];
    if (row.id !== evidence.id || row.card_identity_id !== evidence.card_identity_id
      || row.source_variant_key !== 'holo' || row.canonical_variant_code !== 'holo'
      || row.language_code !== 'en' || row.verification_status !== 'verified') continue;
    valid.add(evidence.source_record_id);
  }
  return valid;
}
